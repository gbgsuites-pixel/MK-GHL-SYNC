// =============================================================================
// SESSION MANAGER — Puppeteer-Direct Architecture (Single-Page Model)
//
// Uses a SINGLE browser tab that navigates between mk and apps domains.
// Both domains share the same browser cookies, so authentication persists.
// The page stays on mk domain for Aura calls, navigates to apps for LWR calls.
//
// This avoids the SSO redirect chain issues that occur when creating a new tab
// for the apps domain (the new tab must re-do SAML authentication).
// =============================================================================

"use strict";

const puppeteer = require("puppeteer");
const fs = require("fs");
const os = require("os");
const path = require("path");
const logger = require("../utils/logger");

const INTOUCH_BASE = process.env.MK_BASE_URL || "https://mk.marykayintouch.com";
const APPS_BASE    = process.env.APPS_BASE_URL || "https://apps.marykayintouch.com";
const LOGIN_URL    = `${INTOUCH_BASE}/s/login/?language=en_US`;

const SESSION_TTL_MS = (parseInt(process.env.SESSION_TTL_HOURS) || 23) * 60 * 60 * 1000;
const LOGIN_MAX_RETRIES = 3;
const LOGIN_RETRY_DELAY_MS = 5000;

// In-memory session cache
const sessionCache = {};
const sessionLocks = new Map();

function withSessionLock(key, task) {
  const previous = sessionLocks.get(key) || Promise.resolve();
  const current = previous.catch(() => {}).then(task);
  sessionLocks.set(key, current);
  return current.finally(() => {
    if (sessionLocks.get(key) === current) sessionLocks.delete(key);
  });
}

function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

function removeUserDataDir(userDataDir) {
  if (!userDataDir) return;
  try {
    fs.rmSync(userDataDir, { recursive: true, force: true });
  } catch (e) {
    logger.warn(`[Login] Browser profile cleanup failed: ${e.message}`);
  }
}

/**
 * Launch Chromium with container-safe flags. The old --single-process and
 * --no-zygote flags are intentionally not used: they can make Chromium fail
 * to start or crash after a Render restart. A second minimal launch profile is
 * retained as a fallback for small changes in the hosted Chromium runtime.
 */
async function launchBrowser(consultantNum) {
  const candidates = [
    {
      label: "standard",
      args: [
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--disable-dev-shm-usage",
        "--disable-gpu",
        "--disable-software-rasterizer",
        "--no-first-run",
        "--no-default-browser-check",
        "--disable-background-networking"
      ]
    },
    {
      label: "minimal",
      args: [
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--disable-dev-shm-usage"
      ]
    }
  ];

  let lastError;

  for (const candidate of candidates) {
    const userDataDir = fs.mkdtempSync(
      path.join(os.tmpdir(), `mk-ghl-${String(consultantNum).toLowerCase()}-`)
    );
    const launchOptions = {
      headless: "new",
      args: candidate.args,
      userDataDir,
      timeout: 60000,
      handleSIGINT: false,
      handleSIGTERM: false,
      handleSIGHUP: false
    };

    if (process.env.PUPPETEER_EXECUTABLE_PATH) {
      launchOptions.executablePath = process.env.PUPPETEER_EXECUTABLE_PATH;
    }

    try {
      const browser = await puppeteer.launch(launchOptions);
      logger.info(`[Login] Chromium launched using ${candidate.label} profile.`);
      return { browser, userDataDir };
    } catch (e) {
      lastError = e;
      removeUserDataDir(userDataDir);
      logger.warn(`[Login] Chromium ${candidate.label} launch failed: ${e.message}`);
    }
  }

  throw new Error(`Chromium launch failed: ${lastError?.message || "unknown launch error"}`);
}

/**
 * Extract the Aura token and context from a request generated by the
 * authenticated Mary Kay page. The current site exposes an empty
 * `$A.clientService.Cc` value, even though its own Aura requests contain a
 * valid token. Capturing the native request is more reliable than reading the
 * internal Aura client-service property.
 */
function parseAuraRequest(request) {
  try {
    const requestUrl = new URL(request.url());
    if (request.method() !== "POST" || !requestUrl.pathname.includes("/s/sfsites/aura")) {
      return null;
    }

    const postData = request.postData() || "";
    const form = new URLSearchParams(postData);
    const auraToken = form.get("aura.token") || "";
    const rawContext = form.get("aura.context") || "";
    let context = {};

    try {
      context = rawContext ? JSON.parse(rawContext) : {};
    } catch (_) {
      context = {};
    }

    let appVersion = "";
    if (context.loaded && typeof context.loaded === "object") {
      for (const [key, value] of Object.entries(context.loaded)) {
        if (key.includes("communityApp") && value) {
          appVersion = String(value);
          break;
        }
      }
    }

    return {
      auraToken,
      fwuid: context.fwuid || "",
      appVersion
    };
  } catch (_) {
    return null;
  }
}

function isCacheValid(consultantNum) {
  const entry = sessionCache[consultantNum];
  if (!entry || !entry.valid) return false;
  return (Date.now() - entry.fetchedAt) < SESSION_TTL_MS;
}

// =============================================================================
// PUPPETEER LOGIN — Single-page model
// =============================================================================

async function loginAndGetSession(consultantNum, password) {
  logger.info(`[Login] Starting Puppeteer login for: ${consultantNum}`);

  let browser;
  let userDataDir = "";

  // Capture the token/context from the page's own Aura requests. Do this
  // before the first navigation so the post-login bootstrap request is not
  // missed. Never log the token itself.
  const capturedAura = {
    auraToken: "",
    fwuid: "",
    appVersion: ""
  };
  const captureAuraRequest = (request) => {
    const data = parseAuraRequest(request);
    if (!data) return;
    // Login/bootstrap requests can legitimately carry the literal `null`
    // placeholder. Keep only a real token and prefer the longest captured
    // value so a later placeholder cannot overwrite the authenticated token.
    if (
      data.auraToken &&
      data.auraToken !== "null" &&
      data.auraToken !== "undefined" &&
      data.auraToken.length >= 20 &&
      data.auraToken.length > capturedAura.auraToken.length
    ) {
      capturedAura.auraToken = data.auraToken;
    }
    if (data.fwuid) capturedAura.fwuid = data.fwuid;
    if (data.appVersion) capturedAura.appVersion = data.appVersion;
  };

  try {
    const launched = await launchBrowser(consultantNum);
    browser = launched.browser;
    userDataDir = launched.userDataDir;
    logger.info(`[Login] Using Chromium at: ${process.env.PUPPETEER_EXECUTABLE_PATH || "Puppeteer default"}`);

    const page = await browser.newPage();
    await page.setUserAgent(
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
    );
    page.on("request", captureAuraRequest);

    // ── STEP 1: Navigate to login page ──
    logger.info(`[Login] Navigating to login page...`);
    await page.goto(LOGIN_URL, {
      waitUntil: "networkidle2",
      timeout: 90000
    });

    // ── STEP 2: Fill credentials ──
    logger.info(`[Login] Filling credentials...`);
    await page.waitForSelector('input[type="text"]',     { timeout: 30000 });
    await page.waitForSelector('input[type="password"]', { timeout: 30000 });
    await page.type('input[type="text"]',     consultantNum, { delay: 60 });
    await page.type('input[type="password"]', password,      { delay: 60 });

    // ── STEP 3: Submit login ──
    logger.info(`[Login] Submitting login form...`);
    try {
      await Promise.all([
        page.waitForNavigation({ waitUntil: "networkidle2", timeout: 60000 }),
        page.keyboard.press("Enter")
      ]);
    } catch (e) {
      logger.warn(`[Login] Navigation timeout (ignored): ${e.message}`);
      await sleep(3000);
    }

    await sleep(3000);

    const postLoginUrl = page.url();
    logger.info(`[Login] Post-login URL: ${postLoginUrl}`);

    if (postLoginUrl.includes("/login")) {
      throw new Error("Login failed — still on login page. Check credentials.");
    }

    // ── STEP 4: Prime a real Aura page ──
    // The home page can expose an empty $A.clientService.Cc value and may not
    // issue a token-bearing request before the session is moved to the Apps
    // domain. Loading Consultant List forces the authenticated Aura bootstrap
    // request, whose body contains the live token and context we capture above.
    try {
      await page.goto(`${INTOUCH_BASE}/s/consultant-list`, {
        waitUntil: "domcontentloaded",
        timeout: 90000
      });
      await sleep(12000);
    } catch (e) {
      logger.warn(`[Login] Consultant List priming navigation issue: ${e.message}`);
    }

    // ── STEP 5: Wait for Aura framework ──
    logger.info(`[Login] Waiting for Aura framework...`);
    try {
      await page.waitForFunction(
        () => typeof $A !== "undefined" && $A.clientService,
        { timeout: 20000 }
      );
      logger.info(`[Login] Aura framework ready.`);
    } catch (e) {
      logger.warn(`[Login] Aura framework not ready — continuing anyway.`);
    }

    // ── STEP 6: Extract Aura metadata and token ──
    logger.info(`[Login] Extracting Aura metadata from mk page...`);

    const auraData = await page.evaluate(() => {
      const result = {
        fwuid: "",
        appVersion: "",
        auraToken: ""
      };

      // Extract fwuid from script tags
      const scripts = document.querySelectorAll("script[src]");
      for (const s of scripts) {
        const src = s.src || "";
        if (src.includes("/auraFW/javascript/")) {
          const m = src.match(/\/auraFW\/javascript\/([^\/]+)\//);
          if (m) result.fwuid = m[1];
        }
      }

      // Extract appVersion from inline scripts
      const inlineScripts = document.querySelectorAll("script:not([src])");
      for (const s of inlineScripts) {
        const t = s.textContent || "";
        if (t.includes("communityApp")) {
          const m = t.match(/siteforce:communityApp['":]\s*['"]?([^'"\\,\s\}]+)/);
          if (m) result.appVersion = m[1];
          if (result.appVersion) break;
        }
      }

      // Extract aura token
      try {
        if (typeof $A !== "undefined" && $A.clientService) {
          result.auraToken = $A.clientService.Cc || "";
          if (!result.auraToken && $A.clientService.token) {
            result.auraToken = $A.clientService.token;
          }
        }
      } catch (e) {
        // Non-fatal
      }

      return result;
    });

    // Prefer the browser-generated request values when the Aura internals are
    // present but no longer expose the token through clientService.Cc.
    const auraToken = auraData.auraToken || capturedAura.auraToken;
    const auraFwuid = auraData.fwuid || capturedAura.fwuid;
    const auraAppVersion = auraData.appVersion || capturedAura.appVersion;

    logger.info(`[Login] auraToken length: ${auraToken.length}`);
    logger.info(`[Login] fwuid: ${auraFwuid ? auraFwuid.substring(0, 20) + "..." : "MISSING"}`);
    logger.info(`[Login] appVersion: ${auraAppVersion || "MISSING"}`);

    if (!auraToken) {
      throw new Error("Aura token unavailable after authenticated Consultant List navigation.");
    }

    // ── STEP 7: Navigate to apps domain (SSO happens naturally with same cookies) ──
    logger.info(`[Login] Navigating to apps domain for Customer List...`);
    let appsSessionValid = false;

    try {
      await page.goto(`${APPS_BASE}/customer-list`, {
        waitUntil: "domcontentloaded",
        timeout: 90000
      });
    } catch (e) {
      logger.warn(`[Login] Apps navigation timeout (non-fatal): ${e.message}`);
    }

    // Wait for SSO redirect chain to complete
    await sleep(15000);

    // Wait until URL stabilizes
    let urlStable = false;
    for (let stabWait = 0; stabWait < 60000; stabWait += 2000) {
      const url1 = page.url();
      await sleep(2000);
      const url2 = page.url();
      if (url1 === url2) {
        urlStable = true;
        break;
      }
    }

    const appsUrl = page.url();
    logger.info(`[Login] Apps URL after wait: ${appsUrl.substring(0, 120)}`);

    if (appsUrl.includes("apps.marykayintouch.com/customer-list")) {
      appsSessionValid = true;
      logger.info(`[Login] Apps page ready at: ${appsUrl.substring(0, 80)}`);
    } else if (appsUrl.includes("apps.marykayintouch.com")) {
      // We're on apps domain but not on customer-list — might be a redirect page
      logger.info(`[Login] On apps domain but not customer-list: ${appsUrl.substring(0, 100)}`);
      // Try navigating to customer-list directly
      try {
        await page.goto(`${APPS_BASE}/customer-list`, {
          waitUntil: "domcontentloaded",
          timeout: 60000
        });
        await sleep(15000);
        const finalUrl = page.url();
        if (finalUrl.includes("apps.marykayintouch.com/customer-list")) {
          appsSessionValid = true;
          logger.info(`[Login] Apps page reached on second try: ${finalUrl.substring(0, 80)}`);
        }
      } catch (e) {
        logger.warn(`[Login] Second navigation attempt failed: ${e.message}`);
      }
    } else {
      // Still on mk domain (SSO redirect back to mk)
      logger.warn(`[Login] SSO redirected back to mk domain: ${appsUrl.substring(0, 100)}`);
      // Try one more time with longer wait
      await sleep(10000);
      try {
        await page.goto(`${APPS_BASE}/customer-list`, {
          waitUntil: "domcontentloaded",
          timeout: 90000
        });
        await sleep(20000);
        const retryUrl = page.url();
        if (retryUrl.includes("apps.marykayintouch.com/customer-list")) {
          appsSessionValid = true;
          logger.info(`[Login] Apps page reached on third try: ${retryUrl.substring(0, 80)}`);
        }
      } catch (e) {
        logger.warn(`[Login] Third navigation attempt failed: ${e.message}`);
      }
    }

    if (!appsSessionValid) {
      logger.warn(`[Login] Warning: Apps page may not have loaded correctly.`);
    }

    // ── STEP 8: Wait for LWR framework to load ──
    if (appsSessionValid) {
      logger.info(`[Login] Waiting for LWR framework to initialize...`);
      try {
        await page.waitForFunction(
          () => {
            try {
              return typeof window.CLWR !== "undefined" &&
                     window.CLWR.serverData !== undefined &&
                     window.CLWR.serverData !== null;
            } catch (e) {
              return false;
            }
          },
          { timeout: 30000 }
        );
        logger.info(`[Login] LWR framework initialized.`);
      } catch (e) {
        logger.warn(`[Login] LWR framework not fully initialized — continuing anyway.`);
      }
    }

    // ── STEP 9: Extract CSRF token from apps page ──
    let appsCsrfToken = "";
    if (appsSessionValid) {
      try {
        appsCsrfToken = await page.evaluate(() => {
          for (const s of document.querySelectorAll("script:not([src])")) {
            const t = s.textContent;
            if (!t.includes("csrfToken")) continue;
            const m = t.match(/"csrfToken"\s*:\s*"(eyJ[^"]+)"/);
            if (m && m[1]) return m[1];
          }
          try {
            if (window.CLWR && window.CLWR.serverData && window.CLWR.serverData.csrfToken)
              return window.CLWR.serverData.csrfToken;
          } catch (e) {}
          return "";
        });
      } catch (e) {}
      logger.info(`[Login] CSRF from DOM: ${appsCsrfToken ? appsCsrfToken.substring(0, 30) + "..." : "MISSING"}`);
    }

    // ── Return session ──
    logger.info(`[Login] ═══ Login successful ═══`);

    return {
      consultantNum:    consultantNum,
      page:             page,       // Single page used for both mk and apps domains
      browser:          browser,
      userDataDir,
      mkUrl:            postLoginUrl,
      appsUrl:          page.url(),
      auraToken,
      auraFwuid,
      auraAppVersion,
      appsCsrfToken:    appsCsrfToken,
      appsSessionValid: appsSessionValid,
      fetchedAt:        new Date().toISOString()
    };

  } catch (err) {
    if (browser) await browser.close().catch(() => {});
    removeUserDataDir(userDataDir);
    throw err;
  }
}

